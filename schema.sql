CREATE DATABASE IF NOT EXISTS ip_dashboard
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE ip_dashboard;

CREATE TABLE IF NOT EXISTS operator_stats (
  operator_name VARCHAR(191) NOT NULL PRIMARY KEY,
  visit_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS vpn_stats (
  vpn_used BOOLEAN NOT NULL PRIMARY KEY,
  visit_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

INSERT INTO vpn_stats (vpn_used, visit_count) VALUES (0, 0), (1, 0)
ON DUPLICATE KEY UPDATE visit_count = visit_count;
